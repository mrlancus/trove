#!/usr/bin/env python3
"""Converts single-line SVG fonts (EMS, from the `hersheytext` npm package) into the compact glyph
table InkHandwriting draws from (docs/plans/sketch-2-plan.md A1).

    python3 -I scripts/glyphs.py path/to/EMSTech.svg tech path/to/EMSAllure.svg script > \
        Packages/TroveCore/Sources/TroveCore/Drawing/InkGlyphData.swift

Each glyph becomes its pen strokes (polylines; curves flattened), in font units with y up.
The fonts are under the SIL Open Font License; their metadata is kept in the output.
"""
import html, json, re, sys

def flatten_cubic(p0, p1, p2, p3, steps=6):
    out = []
    for i in range(1, steps + 1):
        t = i / steps; u = 1 - t
        x = u**3*p0[0] + 3*u*u*t*p1[0] + 3*u*t*t*p2[0] + t**3*p3[0]
        y = u**3*p0[1] + 3*u*u*t*p1[1] + 3*u*t*t*p2[1] + t**3*p3[1]
        out.append((x, y))
    return out

def parse_path(d):
    tokens = re.findall(r'[MLCmlc]|-?[0-9.]+(?:e-?[0-9]+)?', d)
    strokes, cur, i, cmd, pos = [], None, 0, None, (0, 0)
    def num():
        nonlocal i
        v = float(tokens[i]); i += 1; return v
    while i < len(tokens):
        t = tokens[i]
        if t in 'MLCmlc':
            cmd = t; i += 1
            continue
        if cmd in 'Mm':
            x, y = num(), num()
            if cmd == 'm': x, y = pos[0] + x, pos[1] + y
            cur = [(x, y)]; strokes.append(cur); pos = (x, y)
            cmd = 'L' if cmd == 'M' else 'l'
        elif cmd in 'Ll':
            x, y = num(), num()
            if cmd == 'l': x, y = pos[0] + x, pos[1] + y
            cur.append((x, y)); pos = (x, y)
        elif cmd in 'Cc':
            a = (num(), num()); b = (num(), num()); c = (num(), num())
            if cmd == 'c':
                a = (pos[0] + a[0], pos[1] + a[1]); b = (pos[0] + b[0], pos[1] + b[1]); c = (pos[0] + c[0], pos[1] + c[1])
            cur.extend(flatten_cubic(pos, a, b, c)); pos = c
    return [s for s in strokes if len(s) >= 1]

def convert(path):
    svg = open(path, encoding='utf-8').read()
    meta = re.search(r'<metadata>(.*?)</metadata>', svg, re.S).group(1).strip()
    face = re.search(r'<font-face(.*?)/>', svg, re.S).group(1)
    def attr(name, src=face, default=None):
        m = re.search(name + r'="([^"]*)"', src)
        return m.group(1) if m else default
    default_adv = float(re.search(r'<font[^>]*horiz-adv-x="([^"]*)"', svg).group(1))
    glyphs = {}
    for g in re.finditer(r'<glyph([^>]*)/>', svg):
        a = g.group(1)
        ch = attr('unicode', a)
        if ch is None: continue
        ch = html.unescape(ch)
        if len(ch) != 1: continue
        adv = float(attr('horiz-adv-x', a, default_adv))
        d = attr('d', a, '')
        strokes = parse_path(d) if d else []
        glyphs[ch] = {"a": round(adv), "s": [[round(v) for p in s for v in p] for s in strokes]}
    return {"meta": meta, "unitsPerEm": float(attr('units-per-em')), "xHeight": float(attr('x-height')),
            "capHeight": float(attr('cap-height')), "ascent": float(attr('ascent')), "descent": float(attr('descent')),
            "glyphs": glyphs}

args = sys.argv[1:]
fonts = {args[i + 1]: convert(args[i]) for i in range(0, len(args), 2)}
data = json.dumps(fonts, separators=(',', ':'), ensure_ascii=False)
print('// Generated by scripts/glyphs.py from single-line SVG fonts (EMS, SIL Open Font License; see each')
print('// font\'s "meta"). Do not edit by hand.')
print('// swiftlint:disable all')
print('enum InkGlyphData {')
print('    static let json = #"""')
print(data)
print('"""#')
print('}')
